function deepMerge<T extends Record<string, unknown>>(base: T, partial: DeepPartial<T>): T {
  const result: Record<string, unknown> = { ...base }
  for (const key of Object.keys(partial)) {
    const baseVal = base[key]
    const partialVal = (partial as Record<string, unknown>)[key]
    if (
      partialVal &&
      typeof partialVal === 'object' &&
      !Array.isArray(partialVal) &&
      baseVal &&
      typeof baseVal === 'object' &&
      !Array.isArray(baseVal)
    ) {
      result[key] = deepMerge(baseVal as Record<string, unknown>, partialVal as DeepPartial<Record<string, unknown>>)
    } else {
      result[key] = partialVal
    }
  }
  return result as T
}
